import { _decorator, Color, Component, Node, Button, director, Label } from 'cc';
import { 保存存档, 存档 } from '../管理器/存档管理器';
import { 创建普通文字, 播放文本 } from '../方法函数/动画效果';
import { 默认特质表 } from '../默认内容/特质表';
import { 默认天赋表 } from '../默认内容/天赋表';
import { 默认难度表 } from '../默认内容/难度表';
import { 默认套餐表 } from '../默认内容/套餐表';
import {
  计算数值,
  计算最大攻击,
  计算最大生命,
  计算最大逃跑,
  计算最大防御,
} from '../方法函数/属性计算';
import { 默认藏品表 } from '../默认内容/藏品表';
import { 默认技能表 } from '../默认内容/技能表';
import { 计算鱼价格 } from '../公共方法/钓鱼';
import { 对象求和, 格式化金钱 } from '../方法函数/公共函数';
import { 计算得分 } from '../公共方法/最终得分';

const { ccclass, property } = _decorator;

@ccclass('面板')
export class 面板 extends Component {
  @property(Node) 标签: Node = null;
  @property(Node) 分类节点: Node = null;
  @property(Node) 内容: Node = null;
  @property(Node) 返回按钮: Node = null;

  当前分类 = '面板';
  分类列表 = ['面板', '统计', '技能', '战斗'];

  start() {
    this.返回按钮.on(
      Button.EventType.CLICK,
      () => {
        if (globalThis.页面来源 === '特性') {
          director.loadScene('特性');
        } else {
          director.loadScene('主页');
        }
      },
      this,
    );

    this.初始化分类标签();
    this.刷新内容列表();
  }

  初始化分类标签() {
    this.分类列表.forEach((分类名) => {
      const 标签节点 = this.分类节点.getChildByName(分类名);
      if (标签节点) {
        标签节点.on(
          Node.EventType.TOUCH_END,
          () => {
            if (this.当前分类 !== 分类名) {
              this.当前分类 = 分类名;
              this.刷新内容列表();
              this.更新分类标签状态();
            }
          },
          this,
        );
      } else {
      }
    });
    this.更新分类标签状态();
  }

  更新分类标签状态() {
    this.分类列表.forEach((分类名) => {
      const 标签节点 = this.分类节点.getChildByName(分类名);
      if (标签节点) {
        标签节点.getComponent(Label).color = 分类名 === this.当前分类 ? Color.WHITE : Color.GRAY;
      }
    });
  }

  刷新内容列表() {
    switch (this.当前分类) {
      case '面板':
        this.渲染面板列表();
        break;
      case '统计':
        this.渲染统计列表();
        break;
      case '技能':
        this.渲染技能列表();
        break;
      case '战斗':
        this.渲染战斗列表();
        break;
    }
  }

  渲染面板列表() {
    this.内容.removeAllChildren();

    // 存档信息
    创建普通文字(this.内容, '======存档信息======');
    const 难度 = 默认难度表.find((x) => x.名称 === 存档.游戏难度)
    创建普通文字(this.内容, `难度【${存档.游戏难度}】${难度.说明}`, 难度.颜色 || null);
    const 套餐 = 默认套餐表.find((x) => x.名称 === 存档.套餐名称)
    创建普通文字(this.内容, `套餐【${存档.套餐名称}】${套餐.说明}`, 套餐.颜色 || null);

    // 特质信息
    创建普通文字(this.内容, '======特质信息======');
    for (const 特质名 in 存档.特质) {
      if (存档.特质[特质名]) {
        const 特质 = 默认特质表.find((x) => x.名称 === 特质名);
        if (特质) {
          const 文字 = `【${特质.名称}】${特质.说明}`;
          创建普通文字(this.内容, 文字, Color.YELLOW);
        }
      }
    }

    // 天赋信息
    创建普通文字(this.内容, '======天赋信息======');
    for (const 天赋名 in 存档.天赋) {
      if (存档.天赋[天赋名]) {
        const 天赋 = 默认天赋表.find((x) => x.名称 === 天赋名);
        if (天赋) {
          const 文字 = `【${天赋名}】${天赋.说明}`;
          创建普通文字(this.内容, 文字, 天赋.颜色);
        }
      }
    }

    // 藏品信息
    创建普通文字(this.内容, '======藏品信息======');
    for (const 藏品名 in 存档.藏品) {
      if (存档.藏品[藏品名]) {
        const 藏品 = 默认藏品表.find((x) => x.名称 === 藏品名);
        if (藏品) {
          const 文字 = `【${藏品名}${藏品.类型 ? `(${藏品.类型})` : ''}】（当前生效${存档.藏品[藏品名]}个）${藏品.描述}`;
          创建普通文字(this.内容, 文字, 藏品.颜色);
        }
      }
    }

    for (const 新藏品名 in 存档.新藏品) {
      if (存档.新藏品[新藏品名]) {
        const 新藏品 = 默认藏品表.find((x) => x.名称 === 新藏品名);
        if (新藏品) {
          const 文字 = `新获得藏品【${新藏品名}】*${存档.新藏品[新藏品名]}（下局游戏生效）`;
          创建普通文字(this.内容, 文字, 新藏品.颜色);
        }
      }
    }

    // 江湖信息
    if (存档.其他.江湖名气 !== 0) {
      创建普通文字(this.内容, '======江湖信息======');
      const a = `江湖名气：${存档.其他.江湖名气}
江湖残页：${存档.物品.江湖残页}
青竹门声望：${存档.其他.青竹门声望}
铁衣帮声望：${存档.其他.铁衣帮声望}
玄水阁声望：${存档.其他.玄水阁声望}
      `;
      创建普通文字(this.内容, a);
    }

    // 营养信息
    if (存档.套餐名称 === '食补筑基') {
      创建普通文字(this.内容, '======营养信息======');
      //       const 营养信息 = `综合等级：${存档.营养.综合等级}
      // 蛋白质：LV${存档.营养.等级.蛋白质}（${存档.营养.值.蛋白质}）
      // 能量：LV${存档.营养.等级.能量}（${存档.营养.值.能量}）
      // 水分：LV${存档.营养.等级.水分}（${存档.营养.值.水分}）
      // 维生素：LV${存档.营养.等级.维生素}（${存档.营养.值.维生素}）`;
      创建普通文字(this.内容, `内容开发中...`, Color.GREEN);
    }

    // 住房信息
    const 房源 = 存档.临时数据.房源;
    if (房源) {
      创建普通文字(this.内容, '======住房信息======');
      const 住房信息 = `${房源.品质}「${房源.名称}」
地点：${房源.地点}
已居住${存档.其他.住房已居住天数}/${存档.其他.住房天数}天
额外恢复精力：${(房源.恢复精力 * 100).toFixed(2)}%
额外恢复健康：${房源.恢复健康}`;
      创建普通文字(this.内容, 住房信息, Color.BLUE);
    }

    // 钓鱼信息
    const 鱼篓 = 存档.临时数据.鱼篓;
    if (鱼篓 && 鱼篓.length > 0) {
      创建普通文字(this.内容, '======钓鱼信息======');

      鱼篓.forEach((y, i) => {
        const 价格 = 计算鱼价格(y);
        const 星级显示 = y.星级 ? '★'.repeat(y.星级) : '';
        const 结果文本 = `【${y.名称}】「${y.品质}${星级显示}」，重量：${y.重量}kg；预计价格${格式化金钱(价格)}\n<点击出售>`;

        创建普通文字(this.内容, 结果文本, new Color(y.颜色), () => {
          // 增加金钱
          存档.金钱 += 价格;
          // 从鱼篓中移除当前鱼
          存档.临时数据.鱼篓.splice(i, 1);
          // 播放提示
          保存存档();
          播放文本(this.标签, `【${y.名称}】出售成功，获得${格式化金钱(价格)}！`);
          // 重新渲染面板
          this.渲染面板列表();
        });
      });
    }
  }

  渲染技能列表() {
    this.内容.removeAllChildren();

    默认技能表.forEach((技能) => {
      const 等级 = 存档.技能[技能.名称];
      if (等级 > 0) {
        创建普通文字(this.内容, `【${技能.名称}】LV${等级}\n${技能.描述}`);
      }
    });
  }

  渲染统计列表() {
    this.内容.removeAllChildren();

    // 赌博信息
    const 赌博信息 = `======赌博信息======
累计赢钱：${(存档.其他.赌博赢钱总数 / 10).toFixed(1)}元
最多连续成功：${存档.其他.赌博最多连续成功次数}次
当前连续成功：${存档.其他.赌博连续成功次数}次`;
    创建普通文字(this.内容, 赌博信息);

    // 网吧信息
    const 网吧信息 = `======网吧信息======
网吧进度：${存档.其他.网吧进度}
最大连胜次数：${存档.其他.网吧最大连胜次数}次`;
    创建普通文字(this.内容, 网吧信息);

    // 吃饭信息
    const 吃果子次数 = 存档.使用次数.果子 || 0;
    const 吃果子恢复健康数 = 存档.其他.吃果子增加健康数 || 0;
    const 吃果子恢复健康概率 =
      吃果子次数 > 0 ? ((吃果子恢复健康数 / 吃果子次数) * 100).toFixed(1) : '0.0';
    const 吃饭信息 = `======吃饭信息======
吃果子次数：${吃果子次数}
吃果子恢复健康数：${吃果子恢复健康数}（综合概率${吃果子恢复健康概率}%）
吃熟肉次数：${存档.使用次数.熟肉}次
吃巨无霸次数：${存档.使用次数.巨无霸}
吃炒坚果次数：${存档.使用次数.炒坚果}
吃剩饭次数：${存档.使用次数.剩饭}`;
    创建普通文字(this.内容, 吃饭信息);

    // 战斗属性
    const 战斗属性 = `======战斗属性======
暴击率：${计算数值('暴击率')}%
格挡率：${计算数值('格挡率')}%
闪避率：${计算数值('闪避率')}%`;
    创建普通文字(this.内容, 战斗属性);

    // 使用次数
    const 使用次数 = `======使用次数======
使用伤药次数：${存档.使用次数.伤药}
打出子弹次数：${存档.使用次数.子弹}
吸烟次数：${存档.使用次数.香烟}
喝酒次数：${存档.使用次数.啤酒}`;
    创建普通文字(this.内容, 使用次数);

    // 战斗相关
    const 战斗相关 = `======战斗相关======（全属性加成+锻炼加成）
面板攻击：${计算最大攻击()}（${存档.其他.全属性加成}+${存档.其他.锻炼攻击加成}%）
面板防御：${计算最大防御()}（${存档.其他.全属性加成}+${存档.其他.锻炼防御加成}%）
面板生命：${计算最大生命()}（${存档.其他.全属性加成}+${存档.其他.锻炼生命加成}%）
逃跑技术：${计算最大逃跑()}`;
    创建普通文字(this.内容, 战斗相关);

    // 次数统计
    const 次数统计 = `======次数统计======
前进探索次数：${存档.其他.前进探索次数}
事件次数：${存档.其他.随机事件次数}
战斗次数：${存档.其他.战斗总次数}
消灭蚊子数：${存档.其他.消灭蚊子数}
打工成功次数：${存档.其他.打工成功次数}`;
    创建普通文字(this.内容, 次数统计);

    // 其他属性
    const 得分 = 计算得分();
    const 其他属性 = `======其他属性======
当前剧情分：${得分.剧情得分}
罪恶：${存档.罪恶}
阅历：${存档.阅历}
烟瘾：${存档.烟瘾率}
声望：${存档.声望}
战斗经验：${存档.经验}
面试经验：${存档.面经}`;
    创建普通文字(this.内容, 其他属性);
  }

  渲染战斗列表() {
    this.内容.removeAllChildren();

    // 显示总的战斗信息
    const 总胜利次数 = 存档.其他.胜利次数 || 0;
    const 总战败次数 = 存档.其他.战败次数 || 0;
    创建普通文字(this.内容, `总战斗胜利次数：${总胜利次数} / 总战斗失败次数：${总战败次数}`);

    // 收集所有有过战斗记录的敌人名称
    const 敌人名称集合 = new Set<string>();

    // 添加所有有战胜记录的敌人
    for (const 敌人名称 in 存档.击败次数) {
      if (存档.击败次数[敌人名称] > 0) {
        敌人名称集合.add(敌人名称);
      }
    }

    // 添加所有有战败记录的敌人
    for (const 敌人名称 in 存档.战败次数) {
      if (存档.战败次数[敌人名称] > 0) {
        敌人名称集合.add(敌人名称);
      }
    }

    // 如果没有战斗记录，显示提示
    if (敌人名称集合.size === 0) {
      return;
    }

    // 排序并显示所有有战斗记录的敌人
    const 敌人名称列表 = Array.from(敌人名称集合).sort();
    敌人名称列表.forEach((敌人名称) => {
      const 战胜次数 = 存档.击败次数[敌人名称] || 0;
      const 战败次数 = 存档.战败次数[敌人名称] || 0;

      const 文字 = `【${敌人名称}】\n战斗胜利次数：${战胜次数} / 战斗失败次数：${战败次数}`;
      创建普通文字(this.内容, 文字, Color.YELLOW);
    });
  }
}
