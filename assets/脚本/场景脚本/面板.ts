  渲染战斗列表() {
    this.内容.removeAllChildren();

    let index = 0;

    // 显示总的战斗信息
    const 总胜利次数 = 存档.其他.胜利次数 || 0;
    const 总战败次数 = 存档.其他.战败次数 || 0;
    创建普通文字(this.内容, `总战斗胜利次数：${总胜利次数} / 总战斗失败次数：${总战败次数}`, index);
    index++;

    // 收集所有有过战斗记录的敌人名称
    const 敌人名称集合 = new Set<string>();

    // 添加所有有战胜记录的敌人
    for (const 敌人名称 in 存档.击败次数) {
      if (存档.击败次数[敌人名称] > 0) {
        敌人名称集合.add(敌人名称);
      }
    }

    // 添加所有有战败记录的敌人
    for (const 敌人名称 in 存档.战败次数) {
      if (存档.战败次数[敌人名称] > 0) {
        敌人名称集合.add(敌人名称);
      }
    }

    // 如果没有战斗记录，显示提示
    if (敌人名称集合.size === 0) {
      return;
    }

    // 排序并显示所有有战斗记录的敌人
    const 敌人名称列表 = Array.from(敌人名称集合).sort();
    敌人名称列表.forEach((敌人名称) => {
      const 战胜次数 = 存档.击败次数[敌人名称] || 0;
      const 战败次数 = 存档.战败次数[敌人名称] || 0;

      const 文字 = `【${敌人名称}】\n战斗胜利次数：${战胜次数} / 战斗失败次数：${战败次数}`;
      创建普通文字(this.内容, 文字, index, Color.YELLOW);
      index++;
    });
  }
