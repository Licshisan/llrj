import { _decorator, Component, Node, Button, director, tween } from "cc";
import { 存档 } from "../管理器/存档管理器";
import { 保存设置, 设置 } from "../管理器/设置管理器";
import { 创建动画文字, 淡入 } from "../方法函数/动画效果";
import { 获取地区名称 } from "../默认内容/地区表";
const { ccclass, property } = _decorator;

@ccclass('结局')
export class 结局 extends Component {
	@property(Node)
	文本容器: Node = null
	@property(Node)
	继续: Node = null

	结局文本: string[]
	start() {
		if (存档.健康 <= 0) {
			const 地区名 = 获取地区名称()
			if (地区名 === '荒野') {
				this.结局文本 = ["几天后，", "你在草丛中被人发现，", "全身浮肿，面目全非。", "结局——", "【客死他乡】"]
			} else if (地区名 === '县城') {
				this.结局文本 = ["几天后，", "你在草丛中被人发现，", "奄奄一息，身上散发着难闻的味道。", "你立刻被送往救助站。", "父亲当晚从老家赶来，", "你的流浪生涯就此结束。", "结局——", "【无奈的人生】"]
			} else if (地区名 === '山脉') {
				this.结局文本 = ["三日后，", "你在山谷溪边被采药人发现，", "高烧不退，手里还攥着半个果子。", "结局——", "【山雾茫茫】"]
			} else {
				this.结局文本 = ["你在这个能望见万家灯火的桥洞下，", "用捡来的粉笔在地上画了一个大大的蛋糕，", "然后独自唱完了生日歌。", "结局——", "【一个人的庆典】"]
				if (存档.当前地点 === '市中心') {
					this.结局文本 = ["你在一栋水泥骨架的顶层找到避风处，", "用粉笔在墙上写下‘到此一游’，", "却想不出下一个该通知谁。", "结局——", "【无名的留言】"]
				} else if (存档.当前地点 === '郊外') {
					this.结局文本 = ["你倒在郊外废弃的塑料大棚里，", "手里攥着一把野草，", "恍惚中以为那是家里田埂上熟悉的稻穗。", "结局——", "【相似的绿色】"]
				} else if (存档.当前地点 == '城中村') {
					this.结局文本 = ["你在城中村最喧闹的大排档后巷停止了呼吸，", "前街的碰杯声、欢呼声，", "为你奏响了最后一支嘈杂的安魂曲。", "结局——", "【喧嚣的孤独】"]
				} else if (存档.当前地点 == '山洞') {
					this.结局文本 = ["搜救队发现这个山洞时，", "你在最深处睡着了。", "石壁上满是指甲划出的‘正’字，停在第七个的最后一笔。", "结局——", "【未完成的计数】"]
				}
			}
		} else {
			设置.通关次数 += 1
			if (存档.剧情.愿意回家) {
				this.结局文本 = ["推开栅栏，院子里长满了杂草，似乎很久没人居住...（地点：家）", "门是开着的，屋里没有灯火，静悄悄的；", "青灰色的屋顶、几颗新绿色的嫩芽，", "在夕阳的余晖下，显得格外的安静。", "一只猫咪在门前的阳光下打着哈欠（地点：家）", "一个满头白发的老人，忽然呆在了门口...."]
			} else {
				if (存档.伙伴.晓月关系) {
					this.结局文本 = ["一年后，在一座人迹罕至的深山中，", "一间新建的小木屋旁，", "淡青色的花朵在清晨的阳光下、轻盈地跳起了舞蹈。", "这是房子的男主人，给一位短发女孩精心修建的小花园。", "他对女孩说，“我们在这里相守一辈子吧~”"]
				} else if (存档.伙伴.碧瑶好感 > 999) {
					this.结局文本 = ["半年后，冬日的夜幕悄悄降临；在一所大学门口，", "嬉笑的学生三三两两的走出校门。", "橘黄色的路灯下，一个穿着破旧军大衣的男孩、", "安静的等在门口，丝毫不在意旁人异样的眼光。", "不一会儿，一个干干净净、梳着单马尾的女孩，焦急的跑出校门，她停在男孩旁边，微笑着拉起他的手，一起消失在寒冬的夜幕中..."]
				} else if (存档.剧情.住在桥洞) {
					this.结局文本 = ["寒来暑往，你成了这座桥真正的“居民”。", "年轻的流浪者向你讨教生存经验，", "巡警会默契地避开你的“卧室”。", "某个清晨，你在鸟鸣中醒来，", "发现自己已经记不清离家的具体年份。", "结局——", "【桥洞归人】"]
				} else {
					this.结局文本 = ["五十年后，在城中村、一间充满恶臭的破旧出租屋内，", "几名带着消毒面具的消防人员正在清理地上的垃圾。", "房间很小，阴暗而潮湿，墙角堆满了酒瓶和没来得及处理的烟头。", "一位中年消防员拍了拍一个年轻消防员的肩膀责备道，“别看啦，该干活了”。“知道啦。没想到这位奇怪的老人还有这么一段往事啊~”，说完，年轻人把手中发黄的日记本丢进了焚烧箱..."]
				}
			}
		}
		保存设置()

		this.继续.active = false
		const 序列 = tween(this.node).delay(0.8)
		for (let 索引 = 0; 索引 < this.结局文本.length; 索引++) {
			序列.call(() => 创建动画文字(this.文本容器, this.结局文本[索引], 索引)).delay(1.8 / 设置.播放速度).delay(1);
		}
		序列.call(() => 淡入(this.继续))
		序列.start();
		this.继续.on(Button.EventType.CLICK, () => director.loadScene('分数'), this)
	}
}