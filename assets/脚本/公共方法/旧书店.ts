function 随机选择质量() {
  const rand = Math.random();
  if (rand < 0.3) {
    return 质量等级表[0];
  } else if (rand < 0.6) {
    return 质量等级表[1];
  } else if (rand < 0.61) {
    return 质量等级表[2];
  } else {
    return 质量等级表[1];
  }
}

export function 生成旧书店书籍() {
  const rand = Math.random();
  const 数量 = rand < 0.2 ? 1 : rand < 0.4 ? 2 : 3;

  const shuffled = 书籍数据表.sort(() => Math.random() - 0.5);
  return shuffled.slice(0, 数量).map((书籍) => {
    const 质量 = 随机选择质量();
    return {
      书名: 书籍.书名,
      价格: Math.floor(书籍.基础价格 * 质量.价格倍率),
      质量,
      属性加成: 书籍.属性加成,
      学习消耗: 书籍.学习消耗,
      最大进度: 书籍.最大进度,
    };
  });
}

export function 生成旧书店列表(): 商贩项目类型[] {
  const 书籍列表 = 生成旧书店书籍();
  
  return 书籍列表.map((书籍) => ({
    名称: () => {
      if (存档.物品[书籍.书名]) {
        return `《${书籍.书名}》（已拥有）`;
      }
      return `${书籍.质量.名称}的《${书籍.书名}》${(书籍.价格 / 10).toFixed(1)}元`;
    },
    购买: () => {
      if (存档.物品[书籍.书名]) {
        return '你已拥有此书！';
      }
      if (存档.金钱 < 书籍.价格) {
        return '金钱不足！';
      }
      存档.金钱 -= 书籍.价格;
      存档.物品[书籍.书名] = 1;
      if(!存档.临时数据.书籍质量){
        存档.临时数据.书籍质量 = {}
      }
      存档.临时数据.书籍质量[书籍.书名] = 书籍.质量.名称
      return `获得${书籍.质量.名称}的《${书籍.书名}》！请到制作界面使用。`;
    },
  }));
}