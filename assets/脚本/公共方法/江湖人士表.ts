export const 江湖门派列表 = Object.keys(江湖门派表) as 江湖门派名[];
export const 江湖阶层列表: 江湖阶层[] = ["弟子", "精英", "长老", "掌门"];

export function 江湖进度键(门派: 江湖门派名) {
	return `江湖进度_${门派}`;
}

export function 获取江湖进度(门派: 江湖门派名) {
	return 存档.其他[江湖进度键(门派)] || 0;
}

export function 获取虚练等级(功法: string) {
	return 存档.其他[`虚练_${功法}`] || 0;
}

export function 获取江湖敌人名(门派: 江湖门派名, 阶层: 江湖阶层) {
	if (阶层 === "掌门") {
		return `${门派}${江湖门派表[门派].掌门称呼}`;
	}
	return `${门派}${阶层}`;
}

export function 选择江湖门派() {
	const 候选 = 江湖门派列表.filter(门派 => 获取江湖进度(门派) < 4);
	const 列表 = 候选.length ? 候选 : 江湖门派列表;
	return 列表[Math.floor(Math.random() * 列表.length)];
}

export function 选择江湖敌人名(类型: "普通" | "邀斗" | "掌门" = "普通") {
	const 门派 = 选择江湖门派();
	const 进度 = 获取江湖进度(门派);
	if (类型 === "掌门" || 进度 >= 3) {
		return 获取江湖敌人名(门派, "掌门");
	}
	const 阶层 = 类型 === "邀斗" ? 江湖阶层列表[Math.min(进度 + 1, 2)] : 江湖阶层列表[Math.min(进度, 2)];
	return 获取江湖敌人名(门派, 阶层);
}

export function 获得随机残页(数量 = 1) {
	const 门派 = 选择江湖门派();
	const 残页 = 江湖门派表[门派].残页;
	存档.物品[残页] += 数量;
	return 残页;
}

export function 记录江湖胜利(门派: 江湖门派名, 阶层: 江湖阶层) {
	const 配置 = 江湖门派表[门派];
	const 当前进度 = 获取江湖进度(门派);
	const 阶层进度 = 江湖阶层列表.indexOf(阶层) + 1;
	const 名气 = 阶层 === "掌门" ? 8 : 阶层 === "长老" ? 5 : 阶层 === "精英" ? 3 : 1;
	const 残页数量 = 阶层 === "掌门" ? 3 : 阶层 === "长老" ? 2 : 1;

	存档.其他.江湖名气 += 名气;
	存档.其他[`江湖声望_${门派}`] += 名气;
	存档.其他[`江湖击败_${门派}_${阶层}`] += 1;
	存档.物品[配置.残页] += 残页数量;

	let 文本 = `【江湖切磋】击败${获取江湖敌人名(门派, 阶层)}，江湖名气+${名气}，获得「${配置.残页}」*${残页数量}`;
	if (阶层进度 > 当前进度) {
		存档.其他[江湖进度键(门派)] = 阶层进度;
		文本 += `，${门派}进度提升至${阶层进度}/4`;
	}
	if (阶层 === "掌门" && 存档.物品[配置.信物] <= 0) {
		存档.物品[配置.信物] += 1;
		文本 += `，获得门派信物「${配置.信物}」`;
	}
	return 文本;
}

export function 升级虚练功法(门派: 江湖门派名) {
	const 配置 = 江湖门派表[门派];
	const 当前等级 = 获取虚练等级(配置.功法);
	const 残页需求 = 当前等级 + 3;
	const 阅历需求 = 当前等级 * 10;

	if (存档.物品[配置.残页] < 残页需求) {
		return `残页不足，需要「${配置.残页}」${残页需求}张。`;
	}
	if (存档.阅历 < 阅历需求) {
		return `阅历不足，需要${阅历需求}阅历。`;
	}

	存档.物品[配置.残页] -= 残页需求;
	存档.阅历 -= 阅历需求;
	存档.其他[`虚练_${配置.功法}`] = 当前等级 + 1;
	return `虚练「${配置.功法}」提升至LV${当前等级 + 1}。`;
}

export function 获取江湖摘要() {
	const 名气 = 存档.其他.江湖名气 || 0;
	const 最高功法 = 江湖门派列表
		.map(门派 => 江湖门派表[门派].功法)
		.map(功法 => ({ 功法, 等级: 获取虚练等级(功法) }))
		.sort((a, b) => b.等级 - a.等级)[0];
	if (!最高功法 || 最高功法.等级 <= 0) {
		return `江湖名气${名气}`;
	}
	return `江湖名气${名气}，${最高功法.功法}LV${最高功法.等级}`;
}
