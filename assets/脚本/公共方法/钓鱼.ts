function 按权重随机<T extends string>(权重表: Record<T, number>): T {
  const 权重列表 = Object.entries(权重表) as [T, number][];
  const 总权重 = 权重列表.reduce((sum, [, v]) => sum + v, 0);

  let 随机值 = Math.random() * 总权重;

  for (const [键, 权重] of 权重列表) {
    if (随机值 < 权重) return 键;
    随机值 -= 权重;
  }

  return 权重列表[0][0];
}

// ==================== 核心函数1：随机生成鱼（无星阶） ====================
export function 随机生成鱼(指定品质 = null) {
  const 品质 =
    指定品质 && ['普通', '稀有', '史诗', '传说'].includes(指定品质)
      ? 指定品质
      : 按权重随机(品质权重);
  const 候选 = 鱼种数据库.filter((f) => f.品质 === 品质);
  const 鱼种 = 候选[Math.floor(Math.random() * 候选.length)];

  // 重量：在最小和最大重量之间随机
  let 重量 = 鱼种.最小重量 + Math.random() * (鱼种.最大重量 - 鱼种.最小重量);
  重量 = Math.round(重量 * 10) / 10;

  // 难度参数（基于基础难度）
  const 难度基数 = 品质加成[品质];
  let 色块宽度 = Math.min(1.2, Math.max(0.3, 1.2 - 难度基数 * 0.5));
  let 滑块速度 = Math.min(1.5, Math.max(0.6, 0.6 + 难度基数 * 0.5));
  色块宽度 = Math.round(色块宽度 * 100) / 100;
  滑块速度 = Math.round(滑块速度 * 100) / 100;

  return {
    名称: 鱼种.名称,
    品质,
    重量,
    色块宽度,
    滑块速度,
    颜色: 品质颜色[品质],
    星阶: 星阶表[品质],
  };
}

// ==================== 核心函数2：计算价格（无星阶） ====================
export function 计算鱼价格(鱼) {
  const 鱼种 = 鱼种数据库.find((f) => f.名称 === 鱼.名称);
  if (!鱼种) return 0;

  // 基础价格 = 重量 × 单价 × 品质加成
  let 价格 = 鱼.重量 * 1 * 品质加成[鱼.品质];

  // 重量突破奖励（接近最大重量时加成）
  if (鱼.重量 >= 鱼种.最大重量 * 0.92) {
    价格 *= 1 + ((鱼.重量 - 鱼种.最大重量 * 0.92) / (鱼种.最大重量 * 0.08)) * 0.1;
  }

  价格 = Math.max(1, 价格);

  return Math.floor(价格);
}

