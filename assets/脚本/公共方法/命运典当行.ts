export function 准备命运典当行() {
  存档.临时数据.命运典当行 = {
    牺牲列表: 随机抽取多个(命运牺牲表, 3).map((牺牲) => 牺牲.名称),
    天赋列表: 随机抽取多个(获取可典当天赋(), 3).map((天赋) => 天赋.名称),
    已选牺牲: '',
    牺牲结果: '',
  };
}

export function 获取命运牺牲(序号: number) {
  const 牺牲名称 = 存档.临时数据.命运典当行?.牺牲列表?.[序号];
  return 命运牺牲表.find((牺牲) => 牺牲.名称 === 牺牲名称);
}

export function 获取命运天赋(序号: number) {
  const 天赋名称 = 存档.临时数据.命运典当行?.天赋列表?.[序号];
  return 默认天赋表.find((天赋) => 天赋.名称 === 天赋名称);
}

export function 选择命运牺牲(序号: number, 上下文: 事件上下文) {
  const 牺牲 = 获取命运牺牲(序号);
  if (!牺牲) {
    上下文.更改选项('合同被风吹走了');
    return;
  }
  if (牺牲.可以牺牲 && !牺牲.可以牺牲()) {
    上下文.更改选项(牺牲.不可选文本 || '这项牺牲无法支付');
    return;
  }

  存档.临时数据.命运典当行.已选牺牲 = 牺牲.名称;
  存档.临时数据.命运典当行.牺牲结果 = 牺牲.执行();
  上下文.进入事件('命运典当行-选择天赋');
}

export function 选择命运天赋(序号: number, 上下文: 事件上下文) {
  const 天赋 = 获取命运天赋(序号);
  if (!天赋) {
    上下文.更改选项('这格柜台是空的');
    return;
  }

  存档.天赋[天赋.名称] = 计算天赋等级(天赋.名称, 天赋.隐藏 ? 0 : 1);
  执行钩子('激活天赋', [天赋.名称]);
  存档.其他.完成命运典当行 = 1;

  const 牺牲结果 = 存档.临时数据.命运典当行?.牺牲结果 || '';
  存档.临时数据.命运典当行 = null;
  上下文.结束事件(
    `${牺牲结果}\n柜员敲下公章，命运完成过户。你获得天赋【${天赋.名称}】。\n${天赋.说明}`,
  );
}
