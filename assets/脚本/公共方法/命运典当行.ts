function 随机抽取多个<T>(列表: T[], 数量: number): T[] {
  const 候选 = [...列表];
  const 结果: T[] = [];
  while (候选.length > 0 && 结果.length < 数量) {
    结果.push(候选.splice(Math.floor(Math.random() * 候选.length), 1)[0]);
  }
  return 结果;
}

function 获取可典当天赋() {
  return 默认天赋表.filter((i) => {
    const 等级 = 计算天赋等级(i.名称, i.隐藏 ? 0 : 1);
    return !i.负面 && 等级 > 0 && !存档.天赋[i.名称];
  });
}

