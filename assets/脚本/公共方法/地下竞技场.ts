export function 获取竞技场名气配置(名气 = 存档.其他.名气 ): 竞技场名气配置类型 {
	const 档位 = 竞技场名气档位.slice().reverse().find(item => 名气 >= item.所需名气) || 竞技场名气档位[0];
	return {
		名气等级: 档位.名气等级,
		所需名气: 档位.所需名气,
		名气名称: 档位.名气名称,
		出场费: 计算数值("竞技场出场费", 档位.计算出场费(名气)),
	};
}

export function 获取竞技场段位系数(名气 = 存档.其他.名气 ): number {
	return Math.max(1, Math.floor(名气 / 50) + 1);
}

export function 获取竞技场当前名气上限(名气 = 存档.其他.名气 ): number | undefined {
	if (名气 > 300) return undefined;
	if (名气 > 180) return 300;
	if (名气 > 120) return 180;
	if (名气 > 60) return 120;
	if (名气 > 30) return 60;
	return 30;
}

export function 增加竞技场名气(增加值: number) {
	const 当前上限 = 获取竞技场当前名气上限();
	存档.其他.名气 = 存档.其他.名气  + 增加值;
	if (当前上限 && 存档.其他.名气 > 当前上限) {
		存档.其他.名气 = 当前上限;
	}
	return {
		当前名气: 存档.其他.名气 ,
		当前上限,
		到达上限: 当前上限 !== undefined && 存档.其他.名气  === 当前上限,
	};
}

export function 是否竞技场晋级名气(名气 = 存档.其他.名气 ): boolean {
	return 竞技场晋级配置表[名气] !== undefined;
}

export function 获取竞技场比赛名称(): string {
	return 是否竞技场晋级名气() ? "竞技场晋级赛" : "竞技场常规赛";
}

export function 获取竞技场晋级配置(名气 = 存档.其他.名气 ) {
	return 竞技场晋级配置表[名气] || { 阶段: 1, 属性系数: 1 };
}

