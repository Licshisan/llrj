function 深拷贝存档数据(敌人名称: string, 敌人存档数据: unknown): 存档数据类型 | null {
  if (!敌人存档数据 || typeof 敌人存档数据 !== 'object') return null;
  try {
    return 创建默认值代理(JSON.parse(JSON.stringify(敌人存档数据)) as 存档数据类型);
  } catch (e) {
    console.error(`PVP敌人【${敌人名称}】存档数据深拷贝失败:`, e);
    return null;
  }
}

function 执行敌人技能视角(敌人存档: 存档数据类型, 对局: 对局类型, 钩子名称: 时机名称类型) {
  执行存档上下文(敌人存档, () => {
    const 原主角 = 对局.主角;
    const 原敌人 = 对局.敌人;
    对局.主角 = 原敌人;
    对局.敌人 = 原主角;
    try {
      return 执行存档上下文(敌人存档, () => 执行钩子(钩子名称, [对局]));
    } finally {
      对局.主角 = 原主角;
      对局.敌人 = 原敌人;
    }
  });
}

function 创建存档PVP敌人(
  敌人名称: string,
  敌人显示名称: string,
  敌人存档数据: unknown,
  extInfo: 未知对象,
): PVP敌人配置类型 | null {
  const 敌人存档 = 深拷贝存档数据(敌人名称, 敌人存档数据);
  if (!敌人存档) return null;

  const 出场语 = String(extInfo?.出场语 || `是你要挑战我${敌人显示名称}吗？`);
  const 战胜语 = String(extInfo?.战胜语 || '小弟弟也不过如此啦~');
  const 战败语 = String(extInfo?.战败语 || '小弟甘拜下风！');
  const 最大生命 = 执行存档上下文(敌人存档, () => 计算最大生命());

  return {
    名称: 敌人名称,
    显示名称: 敌人显示名称,
    等级: Math.min(Math.floor(敌人存档.经验 / 10), 9999),
    生命: 敌人名称 === '另一个自己' ? 最大生命 : 敌人存档.生命,
    方法: '普攻',
    攻击: 执行存档上下文(敌人存档, () => 计算最大攻击()),
    防御: 执行存档上下文(敌人存档, () => 计算最大防御()),
    最大生命,
    逃跑: 0,
    压制: 执行存档上下文(敌人存档, () => 计算最大压制()),
    增加声望: 3,
    增加属性: 2,
    损失健康: 敌人名称 === '镜像人' ? 10 : 1,
    出场语,
    掉落物: [],
    是否PVP: true,
    PVP敌人存档: 敌人存档,
    其他: {
      存档: 敌人存档,
      金钱: 敌人存档?.金钱 || 0,
      枪开关: false,
      当前架势: '',
      架势使用次数: {},
    },
    战斗初始化: (对局) => {
      执行敌人技能视角(敌人存档, 对局, '战斗初始化');
      return undefined;
    },
    攻击前: (对局) => {
      执行敌人技能视角(敌人存档, 对局, '攻击前');
      return undefined;
    },
    攻击时: (对局) => {
      执行敌人技能视角(敌人存档, 对局, '攻击时');
      return undefined;
    },
    攻击后: (对局) => {
      执行敌人技能视角(敌人存档, 对局, '攻击后');
      return undefined;
    },
    被攻击前: (对局) => {
      执行敌人技能视角(敌人存档, 对局, '被攻击前');
      return undefined;
    },
    被攻击时: (对局) => {
      执行敌人技能视角(敌人存档, 对局, '被攻击时');
      return undefined;
    },
    被攻击后: (对局) => {
      执行敌人技能视角(敌人存档, 对局, '被攻击后');
      return undefined;
    },
    胜利效果: (对局) => {
      对局.结果文本.push(`“${战胜语}”`);
      return undefined;
    },
    失败效果: (对局) => {
      对局.结果文本.push(`“${战败语}”`);
      return undefined;
    },
  };
}

function 创建榜一大哥敌人(): PVP敌人配置类型 {
  const 条目 = 玩家.排行榜?.玩家列表?.[0];
  const 分数 = Math.max(条目?.score || 玩家.扩展信息?.积分 || 1000, 1000);
  const 系数 = Math.min(Math.max(分数 / 1000, 1), 12);
  const 显示名称 = 条目?.玩家?.名称 || '榜一大哥';

  return {
    名称: '榜一大哥',
    显示名称,
    等级: Math.floor(100 + 系数 * 80),
    生命: Math.floor(12000 + 系数 * 8000),
    攻击: Math.floor(900 + 系数 * 650),
    防御: Math.floor(420 + 系数 * 320),
    压制: Math.floor(60 + 系数 * 8),
    损失健康: 3,
    增加声望: 5,
    增加属性: 3,
    方法: '钞能力',
    出场语: `“听说你要挑战榜一？我是${显示名称}，出手吧。”`,
    掉落物: [],
    是否PVP: true,
    其他: {
      金钱: Math.floor(分数 * 2),
      枪开关: false,
      当前架势: '',
      架势使用次数: {},
    },
    攻击时: (对局) => {
      const 追加伤害 = Math.floor(对局.敌人.攻击 * 0.35 + 系数 * 120);
      对局.伤害.最终修正 += 追加伤害;
      return `【榜一大哥使用「钞能力」，追加${追加伤害}点伤害】`;
    },
    被攻击时: (对局) => {
      if (Math.random() * 100 < Math.min(20 + 系数 * 3, 55)) {
        对局.伤害.独立乘区 *= 0.65;
        return '【榜一大哥发动榜首气场，受到的伤害降低】';
      }
    },
    胜利效果: () => '“榜一的位置，不是谁都坐得稳。”',
    失败效果: () => '“不错，这次榜一让你体验一下。”',
  };
}

export function 创建PVP敌人(敌人名称: string): PVP敌人配置类型 | null {
  if (敌人名称 === '时空流浪者') {
    const 数据 = 存档.临时数据.时空流浪者;
    return 创建存档PVP敌人(
      敌人名称,
      数据?.player?.名称 || '时空流浪者',
      数据?.save,
      数据?.player?.扩展信息 || {},
    );
  }
  if (敌人名称 === '镜像人' || 敌人名称 === '另一个自己') {
    return 创建存档PVP敌人(敌人名称, 敌人名称, 存档, 玩家.扩展信息);
  }
  if (敌人名称 === '榜一大哥') {
    return 创建榜一大哥敌人();
  }
  return null;
}
