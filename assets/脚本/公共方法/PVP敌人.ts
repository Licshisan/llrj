function 执行敌人技能视角(敌人存档: any, 对局: 对局类型, 钩子名称: 时机名称类型) {
  执行存档上下文(敌人存档, () => {
    const 原主角 = 对局.主角;
    const 原敌人 = 对局.敌人;
    对局.主角 = 原敌人;
    对局.敌人 = 原主角;
    try {
      return 执行存档上下文(敌人存档, () => 执行钩子(钩子名称, [对局]));
    } finally {
      对局.主角 = 原主角;
      对局.敌人 = 原敌人;
    }
  });
}

function 解析数据(敌人存档数据: any, 敌人玩家数据: any) {
  // 解析存档
  if (!敌人存档数据 || typeof 敌人存档数据 !== 'object') {
    throw new Error(`PVP加载失败！【时空流浪者】敌人存档不存在`);
  }
  let 深拷贝数据;
  try {
    深拷贝数据 = JSON.parse(JSON.stringify(敌人存档数据));
  } catch (e) {
    throw new Error(`PVP加载失败！【时空流浪者】敌人存档解析失败`);
  }
  const 敌人存档: typeof 存档 = 创建默认值代理(深拷贝数据);

  // 解析玩家
  if (!敌人玩家数据 || typeof 敌人玩家数据 !== 'object') {
    throw new Error(`PVP加载失败！【时空流浪者】敌人玩家不存在`);
  }
  let 敌人信息: typeof 玩家;
  try {
    敌人信息 = JSON.parse(JSON.stringify(敌人玩家数据));
  } catch (e) {
    throw new Error(`PVP加载失败！【时空流浪者】敌人玩家解析失败`);
  }

  return { 敌人存档, 敌人信息 };
}

export function 创建时空流浪者() {
  const { 敌人存档, 敌人信息 } = 解析数据(
    存档.临时数据?.时空流浪者?.save,
    存档.临时数据?.时空流浪者?.player,
  );
  const 敌人最大生命 = 执行存档上下文(敌人存档, () => 计算最大生命());
  const 敌人最大攻击 = 执行存档上下文(敌人存档, () => 计算最大攻击());
  const 敌人最大防御 = 执行存档上下文(敌人存档, () => 计算最大防御());
  const 敌人最大精力 = 执行存档上下文(敌人存档, () => 计算最大精力());
  const 天赋列表 = Object.keys(敌人存档.天赋 || {}).filter((名称) => 敌人存档.天赋[名称] > 0);

  // 显示名称
  let 显示名称 = 敌人信息.client_info.name || '时空流浪者';
  if (敌人存档.游戏难度) {
    显示名称 += `[${敌人存档.游戏难度}]`;
  }
  if (敌人信息.server_info.title) {
    显示名称 += `【${敌人信息.server_info.title}】`;
  }

  // 出场语
  let 出场语 = '';
  if (敌人信息.client_info.show_text) {
    出场语 += `“${敌人信息.client_info.show_text}”`;
  } else {
    出场语 += `“是你要挑战我${显示名称}吗？”`;
  }
  出场语 += `\n对方信息【第${敌人存档.天数}天，金钱${格式化金钱(敌人存档.金钱)}，精力${敌人最大精力}，生命${敌人存档.生命}/${敌人最大生命}，攻击${敌人最大攻击}，防御${敌人最大防御}】`;
  if (天赋列表.length > 0) {
    出场语 += '\n检测到对方持有天赋：\n';
    for (const c of 天赋列表) {
      出场语 += `【${c}】\n`;
    }
  }

  return {
    名称: '时空流浪者',
    显示名称,
    等级: Math.min(Math.floor(敌人存档.经验 / 10), 9999),
    生命: 敌人存档.生命,
    方法: '普攻',
    攻击: 敌人最大攻击,
    防御: 敌人最大防御,
    最大生命: 敌人最大生命,
    逃跑: 0,
    压制: 执行存档上下文(敌人存档, () => 计算最大压制()),
    增加声望: 3,
    增加属性: 2,
    损失健康: 3,
    出场语: 出场语,
    掉落物: [],
    战斗初始化: (对局: 对局类型) => {
      执行敌人技能视角(敌人存档, 对局, '战斗初始化');
    },
    攻击前: (对局: 对局类型) => {
      执行敌人技能视角(敌人存档, 对局, '攻击前');
    },
    攻击时: (对局: 对局类型) => {
      执行敌人技能视角(敌人存档, 对局, '攻击时');
    },
    攻击后: (对局: 对局类型) => {
      执行敌人技能视角(敌人存档, 对局, '攻击后');
    },
    被攻击前: (对局: 对局类型) => {
      执行敌人技能视角(敌人存档, 对局, '被攻击前');
    },
    被攻击时: (对局: 对局类型) => {
      执行敌人技能视角(敌人存档, 对局, '被攻击时');
    },
    被攻击后: (对局: 对局类型) => {
      执行敌人技能视角(敌人存档, 对局, '被攻击后');
    },
    胜利效果: (对局: 对局类型) => {
      对局.结果文本.push(敌人信息.client_info?.win_text || '小弟弟也不过如此啦~');
    },
    失败效果: (对局: 对局类型) => {
      对局.结果文本.push(敌人信息.client_info?.fail_text || '小弟甘拜下风！');
    },
    其他: {
      存档: 敌人存档,
      技能点数: 0,
      枪开关: false,
      当前架势: '',
      架势使用次数: {},
      金钱: 敌人存档?.金钱 || 0,
    },
  };
}

