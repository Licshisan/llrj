const 食品店食物表: 食物项目类型[] = 默认食品表.map((食品) => ({
  名称: 食品.名称,
  get 描述() {
    return `※拥有：${存档.物品[食品.名称]}`;
  },
  get 说明() {
    const 营养文本 = 营养列表
      .filter((名称) => 食品.营养[名称])
      .map((名称) => `${名称}+${食品.营养[名称]}`)
      .join(' ');
    return `※效果：摄入营养，睡觉时统一吸收。${营养文本}${食品.特殊效果 ? `。${食品.特殊效果}` : ''}`;
  },
  get 条件() {
    return 存档.物品[食品.名称] > 0;
  },
  get 显示() {
    return 存档.套餐名称 === '吃饭长身体' && 存档.物品[食品.名称] > 0;
  },
  使用: ({ 提示, 食用成功 }) => {
    if (存档.物品[食品.名称] <= 0) {
      提示('食品不足！');
      return;
    }
    食用成功(食用食品(食品.名称));
  },
}));

