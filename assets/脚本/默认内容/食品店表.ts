const 初始营养值 = () => ({ 蛋白质: 0, 能量: 0, 水分: 0, 维生素: 0 });

export function 初始化营养存档() {
	if (!存档.营养) {
		(存档 as any).营养 = {};
	}
	存档.营养.值 = { ...初始营养值(), ...(存档.营养.值 || {}) };
	存档.营养.经验 = { ...初始营养值(), ...(存档.营养.经验 || {}) };
	存档.营养.等级 = { 蛋白质: 1, 能量: 1, 水分: 1, 维生素: 1, ...(存档.营养.等级 || {}) };
	存档.营养.综合经验 = 存档.营养.综合经验 || 0;
	存档.营养.综合等级 = 存档.营养.综合等级 || 1;
}

function 升级所需经验(等级: number) {
	return 100 + 等级 * 30 + 等级 * 等级 * 2;
}

function 升级(当前经验: number, 当前等级: number) {
	let 等级 = 当前等级;
	let 经验 = 当前经验;
	let 升级次数 = 0;
	while (经验 >= 升级所需经验(等级)) {
		经验 -= 升级所需经验(等级);
		等级 += 1;
		升级次数 += 1;
	}
	return { 等级, 经验, 升级次数 };
}

export function 增加营养(营养: Partial<Record<营养名称类型, number>>) {
	初始化营养存档();
	营养列表.forEach((名称) => {
		存档.营养.值[名称] += 营养[名称] || 0;
	});
}

export function 购买食材(食材名称: string, 数量 = 1) {
	const 食材 = 默认食材表.find(item => item.名称 === 食材名称);
	if (!食材) return "没有这种食材。";
	const 花费 = 食材.价格 * 数量;
	if (存档.金钱 < 花费) return "钱不够。";
	存档.金钱 -= 花费;
	存档.物品[食材.名称] += 数量;
	return `购买【${食材.名称}】*${数量}，花费${(花费 / 10).toFixed(1)}元。`;
}

export function 加工食品(食材一: string, 食材二: string) {
	const 配方 = 默认食品表.find(item => {
		const [a, b] = item.食材;
		return (a === 食材一 && b === 食材二) || (a === 食材二 && b === 食材一);
	});
	if (!配方) return "这两个食材暂时做不出像样的食品。";
	if (存档.物品[食材一] <= 0 || 存档.物品[食材二] <= 0) return "食材不足。";
	存档.物品[食材一] -= 1;
	存档.物品[食材二] -= 1;
	存档.物品[配方.名称] += 1;
	return `加工完成，获得【${配方.名称}】*1。`;
}

export function 食用食品(食品名称: string) {
	const 食品 = 默认食品表.find(item => item.名称 === 食品名称);
	if (!食品) return "没有这种食品。";
	if (存档.物品[食品.名称] <= 0) return "食品不足。";
	存档.物品[食品.名称] -= 1;
	增加营养(食品.营养);
	return `食用【${食品.名称}】，摄入${营养列表.map(名称 => `${名称}+${食品.营养[名称] || 0}`).join(" ")}。`;
}

export function 执行营养睡觉结算(结果文本: string[]) {
	初始化营养存档();
	const 达标数量 = 营养列表.filter(名称 => 存档.营养.值[名称] >= 每日需求[名称]).length;
	const 均衡倍率 = 0.7 + 达标数量 * 0.08;
	let 吸收倍率 = 1;
	if (存档.饥饿 < 15) 吸收倍率 -= 0.2;
	if (存档.饥饿 <= 0) 吸收倍率 -= 0.3;
	if (存档.健康 < 40) 吸收倍率 -= 0.15;
	吸收倍率 = Math.max(0.35, 吸收倍率);

	const 达标文本 = 营养列表.map(名称 => `${名称}${存档.营养.值[名称] >= 每日需求[名称] ? "达标" : "不足"}`).join("，");
	结果文本.push(`【日常代谢】你睡了一觉，身体开始吸收今天摄入的营养。${达标文本}。`);

	let 单项基础经验总和 = 0;
	const 经验文本: string[] = [];
	const 升级文本: string[] = [];
	营养列表.forEach((名称) => {
		const 今日营养 = 存档.营养.值[名称];
		const 达标经验 = Math.min(今日营养, 每日需求[名称]) * 10;
		const 超量经验 = Math.min(Math.max(今日营养 - 每日需求[名称], 0), 每日需求[名称]) * 3;
		const 基础经验 = 达标经验 + 超量经验;
		const 最终经验 = Math.floor(基础经验 * 均衡倍率 * 吸收倍率);
		单项基础经验总和 += 基础经验;
		存档.营养.经验[名称] += 最终经验;
		经验文本.push(`${名称}经验+${最终经验}`);

		const 单项升级 = 升级(存档.营养.经验[名称], 存档.营养.等级[名称]);
		if (单项升级.升级次数 > 0) {
			存档.营养.等级[名称] = 单项升级.等级;
			存档.营养.经验[名称] = 单项升级.经验;
			升级文本.push(`${名称}LV${单项升级.等级}`);
			if (名称 === "蛋白质") {
				存档.攻击 += 单项升级.升级次数;
				存档.防御 += 单项升级.升级次数;
			}
			if (名称 === "能量") 存档.最大饥饿 += 单项升级.升级次数 * 2;
			if (名称 === "水分") 存档.最大生命 += 单项升级.升级次数 * 8;
			if (名称 === "维生素") 存档.健康 += 单项升级.升级次数;
		}
	});

	const 综合经验 = Math.floor(单项基础经验总和 * 0.25 * 均衡倍率 * 吸收倍率);
	存档.营养.综合经验 += 综合经验;
	const 综合升级 = 升级(存档.营养.综合经验, 存档.营养.综合等级);
	if (综合升级.升级次数 > 0) {
		存档.营养.综合等级 = 综合升级.等级;
		存档.营养.综合经验 = 综合升级.经验;
		存档.最大精力 += 综合升级.升级次数 * 3;
		升级文本.unshift(`综合营养LV${综合升级.等级}`);
	}

	结果文本.push(`【营养吸收】${经验文本.join(" ")} 综合营养经验+${综合经验}。`);
	if (升级文本.length > 0) {
		结果文本.push(`【等级提升】${升级文本.join("，")}。`);
	}

	营养列表.forEach((名称) => {
		存档.营养.值[名称] = Math.max(0, Math.floor((存档.营养.值[名称] - 每日需求[名称]) * 保留率[名称]));
	});
}

export function 获取营养摘要() {
	初始化营养存档();
	return `营养 综合LV${存档.营养.综合等级} 蛋${存档.营养.等级.蛋白质}/能${存档.营养.等级.能量}/水${存档.营养.等级.水分}/维${存档.营养.等级.维生素}`;
}
