const 藏品颜色表: Record<藏品类型, Color> = {
  普通: new Color(255, 255, 255),
  稀有: new Color(0, 180, 255),
  史诗: new Color(255, 100, 255),
  传说: new Color(255, 215, 0),
};
const 藏品掉落概率表: Record<藏品类型, number> = { 普通: 0.01, 稀有: 0.1, 史诗: 1, 传说: 10 };
const 难度掉落倍率表: Record<string, number> = { 普通: 1, 试炼: 1.5, 真实: 2, 残酷: 2.5, 绝境: 3 };

function 增强字段(藏品: 藏品定义类型, 类别: 藏品类型): 藏品定义类型 {
  const 原始效果 = 藏品.效果 || {};
  const 类型 = 藏品.类型 || 类别;
  return {
    ...藏品,
    颜色: 藏品颜色表[类型],
    类型,
    效果: {
      ...原始效果,
      战斗胜利: (对局) => {
        原始效果.战斗胜利?.(对局);
        if (!藏品.敌人 || !藏品.说明) return;
        if (对局.敌人.名称 !== 藏品.敌人) return;
        const 概率 = 计算数值(
          '藏品掉落概率',
          藏品掉落概率表[类型] * (难度掉落倍率表[存档.游戏难度] ?? 1),
        );
        if (Math.random() * 100 >= 概率) return;
        const 套餐 = 默认套餐表.find((套餐) => 套餐.名称 === 存档.套餐名称);
        if (套餐?.娱乐) return;
        存档.新藏品[藏品.名称] = (存档.新藏品[藏品.名称] || 0) + 1;
        对局.结果文本.push(藏品.说明);
      },
    },
  };
}

