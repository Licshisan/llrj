interface 默认效果项类型<时机 extends keyof 通用效果字段类型 & string> {
  时机: 时机;
  函数: NonNullable<通用效果字段类型[时机]>;
}

function 定义效果<时机 extends keyof 通用效果字段类型 & string>(效果: 默认效果项类型<时机>) {
  return 效果;
}

