          const 反震伤害 = Math.floor(((对局.敌人.攻击 - 对局.敌人.防御) * 铁衣功强度) / 100);
          对局.敌人.生命 -= 反震伤害;
          对局.结果文本.push(`【「伪反震」对${对局.敌人.显示名称}造成${反震伤害}点伤害】`);
