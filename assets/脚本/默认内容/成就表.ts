// 计算排行榜积分总和的钩子函数
export function 计算排行榜积分总和(): number {
  let 总积分 = 0;
  // 遍历所有成就，检查是否已完成，并累加积分
  默认成就表.forEach((成就) => {
    if (成就.积分 && 已完成成就(成就.名称)) {
      总积分 += 成就.积分;
    }
  });
  return 总积分;
}
