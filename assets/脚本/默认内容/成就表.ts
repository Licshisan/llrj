export function 解锁特质(成就名称: string) {
    const 成就特质对照表 = {
        "强而有力": "强而有力",
        "精力充沛": "精力充沛",
        "果子杀手": "营养亲和",
        "县城霸主": "县城霸主",
        "鸿运赌客": "鸿运赌客",
        "灭蚊专家": "灭蚊专家",
        "钢铁意志": "钢铁意志",
        "均衡发育": "均衡发育",
    };

    const 特质名 = 成就特质对照表[成就名称];
    if (!特质名) return; 

    if (!设置.特质[特质名]) {
        设置.特质[特质名] = 1;
    } else {
        设置.特质[特质名] += 1;
    }

    log(`【特质解锁】${特质名} 等级提升至 ${设置.特质[特质名]}`);
}

export function 更新成就(): 成就项目类型[] {
	try {
		const 成就字符串 = sys.localStorage.getItem("成就");
		let 本地成就表: 成就项目类型[] = [];
		if (成就字符串) {
			try {
				本地成就表 = JSON.parse(成就字符串) as 成就项目类型[];
				if (!Array.isArray(本地成就表)) 本地成就表 = [];
			} catch (e) {
				warn("「成就系统」本地成就数据解析失败，重置为空数组：", e);
				本地成就表 = [];
			}
		}

		const 新成就表: 成就项目类型[] = [];
		const 新完成的成就: 成就项目类型[] = []; // 只返回新完成的成就

		默认成就表.forEach((全局成就项) => {
			const 本地成就项 = 本地成就表.find(item => item?.名称 === 全局成就项.名称);

			if (本地成就项) {
				// 检查是否是新完成的（之前未达成，现在达成了）
				const 之前已达成 = 本地成就项.达成时间 !== undefined;
				const 现在已达成 = 全局成就项.条件;
				if (!之前已达成 && 现在已达成) {
					新完成的成就.push({
						...本地成就项,
						描述: 全局成就项.描述,
						奖励: 全局成就项.奖励,
						条件: true,
						达成时间: Date.now()
					});
					解锁特质(全局成就项.名称);
					设置.成就[全局成就项.名称] = true; // 同步设置状态
				}

				新成就表.push({
					...本地成就项,
					描述: 全局成就项.描述,
					条件: 全局成就项.条件,
					...(全局成就项.条件 && !本地成就项.达成时间 && { 达成时间: Date.now() }) // 仅首次达成时记录时间
				});
			} else {
				// 全新的成就，如果条件满足，则是新完成的
				if (全局成就项.条件) {
					新完成的成就.push({
						名称: 全局成就项.名称,
						描述: 全局成就项.描述,
						奖励: 全局成就项.奖励,
						条件: true,
						达成时间: Date.now()
					});
					解锁特质(全局成就项.名称);
					设置.成就[全局成就项.名称] = true; // 同步设置状态
				}
				
				新成就表.push({
					名称: 全局成就项.名称,
					描述: 全局成就项.描述,
					条件: 全局成就项.条件,
					达成时间: 全局成就项.条件 ? Date.now() : undefined
				});
			}
		});
		保存设置();
		sys.localStorage.setItem("成就", JSON.stringify(新成就表));
		log(`「成就系统」更新完成，本次新完成成就：${新完成的成就.length}项`);
		return 新完成的成就; // 只返回新完成的成就
	} catch (e) {
		error("「成就系统」更新失败：", e);
		return [];
	}
}

