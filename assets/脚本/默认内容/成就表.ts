export function 已完成成就(检查名称: string) {
  if (Array.isArray(玩家.client_info?.achievements))
    return 玩家.client_info?.achievements.some((成就) => 成就.name === 检查名称);
  const 旧成就对象 = 玩家.client_info?.achievements || {};
  return Object.keys(旧成就对象).some((成就名) => 成就名 === 检查名称);
}

function 获得藏品(藏品名: string) {
  玩家.client_info.collections ||= {};
  玩家.client_info.collections[藏品名] = (玩家.client_info.collections[藏品名] || 0) + 1;
}

function 获取先驱(成就名: string) {
  if (!Array.isArray(玩家.pioneers)) return undefined;
  return 玩家.pioneers.find((先驱) => 先驱.name === 成就名 || 先驱.description === 成就名);
}

function 是当前玩家先驱(成就名: string) {
  return 获取先驱(成就名)?.player_id === 玩家.id;
}

function 获取先驱完成时间(先驱: ReturnType<typeof 获取先驱>) {
  const 完成时间 = 先驱?.created_at ? new Date(先驱.created_at).getTime() : 0;
  return Number.isFinite(完成时间) ? 完成时间 : 0;
}

